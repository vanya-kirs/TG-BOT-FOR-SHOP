import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {getMigrations} from 'better-auth/db/migration';
import {createIdentity} from '../server/auth.mjs';
import {createApp} from '../server/app.mjs';
import {migrateBrands} from '../server/brands.mjs';

test('HTTP sessions and role checks reject anonymous access and cross-origin writes',async t=>{
 const letters=[];
 const identity=createIdentity({APP_URL:'http://localhost:4173',BETTER_AUTH_SECRET:randomBytes(48).toString('base64'),DATABASE_PATH:':memory:'},{sendMail:async mail=>letters.push(mail)});
 await (await getMigrations(identity.options)).runMigrations();
 migrateBrands(identity.database);
 const server=createApp(identity).listen(0,'127.0.0.1');
 await new Promise((resolve,reject)=>{server.once('listening',resolve);server.once('error',reject);});
 t.after(async()=>{await new Promise(resolve=>server.close(resolve));identity.database.close();});
 const origin=`http://127.0.0.1:${server.address().port}`;
 const get=(path,cookie='')=>fetch(origin+path,{headers:{cookie}});
 const post=(path,body,source='http://localhost:4173')=>fetch(origin+path,{method:'POST',headers:{Origin:source,'Content-Type':'application/json'},body:JSON.stringify((path.endsWith('sign-up/email')||path.endsWith('sign-in/social'))?{...body,acceptPersonalData:true,consentVersion:'2026-11-19-v1'}:body)});
 assert.equal((await get('/api/me')).status,401);
 assert.equal((await get('/api/access/admin')).status,401);
 assert.equal((await (await get('/api/brands')).json()).length,626);
 assert.equal((await post('/api/brands',{name:'QA brand'})).status,401);
 const values={email:'http@example.com',name:'Тест',password:'test-passphrase-long-42'};
 assert.equal((await post('/api/auth/sign-up/email',values,'https://attacker.example')).status,403);
 assert.equal((await post('/api/auth/sign-up/email',values)).status,200);
 await post('/api/auth/email-otp/send-verification-otp',{email:values.email,type:'email-verification'});
 await post('/api/auth/email-otp/verify-email',{email:values.email,otp:letters[0].text.match(/\b\d{6}\b/)[0]});
 const login=await post('/api/auth/sign-in/email',values);
 assert.equal(login.status,200);
 const cookie=login.headers.getSetCookie().map(c=>c.split(';')[0]).join('; ');
 const me=await get('/api/me',cookie);
 assert.equal(me.headers.get('cache-control'),'no-store');
 assert.equal((await me.json()).user.role,'customer');
 assert.equal((await get('/api/access/admin',cookie)).status,403);
 assert.equal((await get('/api/access/supplier',cookie)).status,403);
 const changeBrand=(path,body,method='POST')=>fetch(origin+path,{method,headers:{Origin:'http://localhost:4173','Content-Type':'application/json',cookie},...(body?{body:JSON.stringify((path.endsWith('sign-up/email')||path.endsWith('sign-in/social'))?{...body,acceptPersonalData:true,consentVersion:'2026-11-19-v1'}:body)}:{})});
 assert.equal((await changeBrand('/api/brands',{name:'QA brand'})).status,403);
 identity.database.prepare('UPDATE user SET role=? WHERE email=?').run('admin',values.email);
 const created=await changeBrand('/api/brands',{name:'QA brand',aliases:['QA alias'],categories:['Одежда','Сумки']});assert.equal(created.status,201);
 const brand=await created.json();
 assert.equal((await changeBrand('/api/brands',{name:'QA alias'})).status,400);
 assert.equal((await changeBrand('/api/brands/'+brand.id,{name:'QA renamed',aliases:['QA alias'],categories:['Сумки']},'PUT')).status,200);
 assert.equal((await changeBrand('/api/brands/'+brand.id,null,'DELETE')).status,200);
 migrateBrands(identity.database);assert.equal((await (await get('/api/brands')).json()).length,626);
 assert.equal((await get('/.env')).status,404);
 assert.equal((await get('/server/auth.mjs')).status,404);
});
