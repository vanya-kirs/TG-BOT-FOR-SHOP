import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {getMigrations} from 'better-auth/db/migration';
import {createIdentity} from '../server/auth.mjs';

test('real registration, email confirmation, login, logout and password recovery',async()=>{
 const letters=[];
 const identity=createIdentity({APP_URL:'http://localhost:4173',BETTER_AUTH_SECRET:randomBytes(48).toString('base64'),DATABASE_PATH:':memory:'},{sendMail:async mail=>letters.push(mail),authOptions:{rateLimit:{enabled:false}}});
 await (await getMigrations(identity.options)).runMigrations();
 const call=(path,body,cookie='')=>identity.auth.handler(new Request('http://localhost:4173/api/auth/'+path,{method:body?'POST':'GET',headers:{Origin:'http://localhost:4173','Content-Type':'application/json',Cookie:cookie},...(body?{body:JSON.stringify((path.endsWith('sign-up/email')||path.endsWith('sign-in/social'))?{...body,acceptPersonalData:true,consentVersion:'2026-11-19-v1'}:body)}:{})}));
 const cookies=response=>response.headers.getSetCookie().map(v=>v.split(';')[0]).join('; ');
 const credentials={email:'test@example.com',password:'correct-horse-battery-42'};
 let response=await call('sign-up/email',{...credentials,name:'Покупатель',role:'admin',supplierId:'s1'});
 assert.equal(response.status,400);
 response=await call('sign-up/email',{...credentials,name:'Покупатель'});
 assert.equal(response.status,200,await response.clone().text());
 assert.equal((await call('email-otp/send-verification-otp',{email:credentials.email,type:'email-verification'})).status,200);
 assert.equal(letters.length,1);
 assert.equal(identity.database.prepare('SELECT role FROM user').get().role,'customer');
 assert.equal(identity.database.prepare('SELECT supplierId FROM user').get().supplierId,null);
 const stored=identity.database.prepare('SELECT password FROM account').get().password;
 assert.notEqual(stored,credentials.password);
 response=await call('sign-in/email',credentials);
 assert.equal(response.status,403);
 response=await call('email-otp/verify-email',{email:credentials.email,otp:letters[0].text.match(/\b\d{6}\b/)[0]});
 assert.equal(response.status,200,await response.clone().text());
 response=await call('sign-in/email',{...credentials,password:'incorrect-password'});
 assert.equal(response.status,401);
 response=await call('sign-in/email',credentials);
 assert.equal(response.status,200,await response.clone().text());
 const cookie=cookies(response);
 assert.match(response.headers.get('set-cookie'),/HttpOnly/i);
 let session=await (await call('get-session',null,cookie)).json();
 assert.equal(session.user.role,'customer');
 await call('sign-out',{},cookie);
 assert.equal(await (await call('get-session',null,cookie)).json(),null);
 response=await call('sign-in/email',credentials);
 const oldCookie=cookies(response);
 response=await call('request-password-reset',{email:credentials.email,redirectTo:'http://localhost:4173/?auth=reset'});
 assert.equal(response.status,200);
 const resetLink=letters.at(-1).text.match(/http[^\s]+/)[0];
 response=await identity.auth.handler(new Request(resetLink));
 const resetURL=new URL(response.headers.get('location'));
 const token=resetURL.searchParams.get('token');
 assert.ok(token);
 response=await call('reset-password',{token,newPassword:'different-password-42'});
 assert.equal(response.status,200,await response.clone().text());
 assert.equal(await (await call('get-session',null,oldCookie)).json(),null);
 assert.equal((await call('reset-password',{token,newPassword:'third-password-42'})).status,400);
 assert.equal((await call('sign-in/email',credentials)).status,401);
 assert.equal((await call('sign-in/email',{...credentials,password:'different-password-42'})).status,200);
 identity.database.close();
});

test('missing mail and OAuth configuration never pretend to be available',()=>{
 const identity=createIdentity({APP_URL:'http://localhost:4173',BETTER_AUTH_SECRET:randomBytes(48).toString('base64'),DATABASE_PATH:':memory:'});
 assert.deepEqual(identity.capabilities,{server:true,email:false,providers:{google:false,yandex:false,telegram:false}});
 assert.equal(identity.options.rateLimit.enabled,true);
 assert.equal(identity.options.account.accountLinking.disableImplicitLinking,false);
 identity.database.close();
 assert.throws(()=>createIdentity({BETTER_AUTH_SECRET:'short'}));
});
