import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {getMigrations} from 'better-auth/db/migration';
import {createIdentity} from '../server/auth.mjs';

test('verification codes expire, are single-use, and enforce mailbox cooldown before replacement',async t=>{
 const letters=[];
 const identity=createIdentity({APP_URL:'http://localhost:4173',BETTER_AUTH_SECRET:randomBytes(48).toString('hex'),DATABASE_PATH:':memory:'},{sendMail:async mail=>letters.push(mail),authOptions:{rateLimit:{enabled:false}}});
 t.after(()=>identity.database.close());
 await (await getMigrations(identity.options)).runMigrations();
 const email='otp@example.com';
 const call=(path,body)=>identity.auth.handler(new Request('http://localhost:4173/api/auth/'+path,{method:'POST',headers:{Origin:'http://localhost:4173','Content-Type':'application/json'},body:JSON.stringify((path.endsWith('sign-up/email')||path.endsWith('sign-in/social'))?{...body,acceptPersonalData:true,consentVersion:'2026-11-19-v1'}:body)}));
 const send=()=>call('email-otp/send-verification-otp',{email,type:'email-verification'});
 const verify=otp=>call('email-otp/verify-email',{email,otp});
 const code=()=>letters.at(-1).text.match(/\b\d{6}\b/)[0];
 assert.equal((await call('sign-up/email',{email,name:'Тест',password:'1234567'})).status,400);
 assert.equal((await call('sign-up/email',{email,name:'Тест',password:'12345678'})).status,200);
 assert.equal(letters.length,0);
 assert.equal((await send()).status,200);
 assert.match(letters[0].html,/VERA PRIVÉ/);
 assert.match(letters[0].html,/5 минут/);
 const first=code();
 let stored=identity.database.prepare('SELECT * FROM verification').get();
 assert.ok(!stored.value.includes(first));
 assert.ok(Math.abs(new Date(stored.expiresAt).getTime()-Date.now()-300000)<3000);
 const blocked=await send();
 assert.equal(blocked.status,429);
 assert.ok(Number(blocked.headers.get('retry-after'))<=60);
 assert.equal(letters.length,1);
 assert.equal(identity.database.prepare('SELECT value FROM verification').get().value,stored.value);
 assert.equal((await verify(first==='000000'?'111111':'000000')).status,400);
 identity.database.prepare('UPDATE verification SET expiresAt=?').run(Date.now()-1000);
 assert.equal((await verify(first)).status,400);
 identity.database.prepare('UPDATE otp_cooldown SET next_at=0').run();
 assert.equal((await send()).status,200);
 const second=code();
 assert.equal(letters.length,2);
 const verified=await verify(second);
 assert.equal(verified.status,200);
 assert.match(verified.headers.get('set-cookie'),/HttpOnly/);
 assert.equal((await verify(second)).status,400);
 assert.equal((await call('sign-in/email',{email,password:'12345678'})).status,200);
 assert.equal((await call('email-otp/send-verification-otp',{email,type:'sign-in'})).status,400);
 assert.equal((await call('sign-in/email-otp',{email,otp:second})).status,403);
 identity.database.prepare('UPDATE otp_cooldown SET next_at=0').run();
 await send();
 identity.database.prepare('UPDATE otp_cooldown SET next_at=0').run();
 await send();
 assert.equal(identity.database.prepare('SELECT count(*) AS n FROM verification WHERE identifier=?').get('email-verification-otp-'+email).n,1);
 const latest=code(),wrong=latest==='000000'?'111111':'000000';
 for(let i=0;i<5;i++)assert.equal((await verify(wrong)).status,400);
 assert.equal((await verify(latest)).status,403);

});
